// Dithering for the places the image is cut to 8 bits: blue noise for the
// window, an 8x8 ordered (Bayer) map for the cache capture.
//
// The neural output is linear FP16. Before this, the window present quantised
// it straight into an R8G8B8A8 backbuffer and the cache capture straight into
// B8G8R8A8 (or 8-bit NV12), each with round-to-nearest: a smooth dark gradient
// the model lifts becomes a staircase of flat bands one code value apart, and
// nothing downstream can put back the slope that rounding threw away.
//
// Ordered dithering against a blue-noise threshold map fixes that. Each pixel
// is quantised as floor(value * 255 + t) with t in (0,1) taken from a tiled
// 64x64 map, so the expected output is exactly the input: a band edge turns
// into a spatial mix of the two codes, in the proportion the unquantised value
// sits between them. The map is blue noise - void-and-cluster (Ulichney 1993),
// sigma 1.5, seed 20260923 - because its error energy sits at the highest
// spatial frequencies, where the eye is least sensitive; libplacebo's default
// dither is the same construction at the same size. The measured spectrum puts
// 0.0014 % of this map's energy below a quarter of Nyquist, against 5.2 % for
// white noise.
//
// The pattern is static: frame N and frame N+1 use the same map. A per-frame
// offset would trade the residual pattern for temporal noise, which is flicker
// in a player and bitrate in an encoder, and neither is wanted here.
//
// One threshold per pixel is shared by all three channels, so the dither adds
// no chroma noise of its own.
//
// The window's dither is the compositor's last step but one: it is added to the
// encoded value the backbuffer stores, scaled by (1 - the subtitle overlay's
// coverage), which equals dithering the picture before the subtitles go over it.
// The video under and around the text is dithered; an opaque glyph is not. An HDR
// backbuffer (R10G10B10A2, PQ) takes the same map at its own 10-bit code, +-half
// of 1/1023: a smooth dark gradient bands there too, only finer, and the offset
// costs nothing the eye can see.
//
// The cache capture does NOT use this map, on a measurement. Its frames go on
// to HEVC at CQ 16, and an encoder spends its quantiser on exactly the highest
// spatial frequencies blue noise puts its energy in: cutting a Lossless render
// to 8 bits with this map scored CAMBI 0.05 on the gradient clip (banding gone;
// the 10-bit reference itself scores 0.23), and 5.73 once through the Standard
// rung's NVENC, against 6.46 for plain rounding - the dither was all but
// erased. The same cut with an 8x8 Bayer map scored 0.50 before the encoder and
// 1.62 after it, and 2.33 against 5.95 for rounding on the film clip; a tile of
// period 8 lands on a handful of transform coefficients that survive the
// quantiser. The window has no encoder after it, so it keeps blue noise, which
// leaves the least visible pattern.
//
// Through the worker the ordered capture dither cut the Standard rung's CAMBI
// by 44-63 % on the three fixture clips with banding (10.6 -> 4.5 on the
// gradients) at an unchanged size, with VMAF within -0.04..+0.03 and output
// flicker within 0.007 codes. It stays off by default because those deltas,
// though far below visibility, are not all zero, and the bar for defaulting a
// cache-changing switch on is no regression at all. The High rung removes the
