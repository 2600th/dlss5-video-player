inline constexpr uint32_t kBlueNoiseSize = 64;
inline constexpr uint32_t kBlueNoiseWords[1024] = {DLSS_BLUE_NOISE_64x64};

// The 8-bit rank at (x, y), tiled. Mirrors DitherOffset8 in the shader.
constexpr uint32_t BlueNoiseRank(uint32_t x, uint32_t y)
{
    const uint32_t index = (y % kBlueNoiseSize) * kBlueNoiseSize + (x % kBlueNoiseSize);
    return (kBlueNoiseWords[index >> 2] >> ((index & 3u) * 8u)) & 0xFFu;
}

// Offset added before a round-to-nearest UNORM store, in units of one code
// value: (rank + 0.5) / 256 - 0.5, so in (-0.5, 0.5) and zero on average.
constexpr float BlueNoiseOffset(uint32_t x, uint32_t y)
{
    return (static_cast<float>(BlueNoiseRank(x, y)) + 0.5f) / 256.0f - 0.5f;
}

// The capture's map: the classic 8x8 ordered-dither (Bayer) index, built from
// the bits of x ^ y and y interleaved and reversed, so no table is needed.
// Every value 0..63 appears once per tile. Mirrors DitherOffsetBayer8 in the
// shader, bit for bit.
constexpr uint32_t Bayer8Rank(uint32_t x, uint32_t y)
{
    const uint32_t d = (x ^ y) & 7u;
    const uint32_t v = y & 7u;
    return ((d & 1u) << 5) | ((v & 1u) << 4) | ((d & 2u) << 2) | ((v & 2u) << 1) |
           ((d & 4u) >> 1) | ((v & 4u) >> 2);
}

// (rank + 0.5) / 64 - 0.5 of a code value, zero on average over a tile.
constexpr float Bayer8Offset(uint32_t x, uint32_t y)
{
    return (static_cast<float>(Bayer8Rank(x, y)) + 0.5f) / 64.0f - 0.5f;
}

enum class DitherMap { BlueNoise, Bayer8 };

// What a round-to-nearest store of `value` (0..1) at `maxCode` + 1 codes keeps,
// with the dither applied first. Mirrors DITHER_STORE (maxCode 255 for an SDR
// backbuffer, 1023 for an HDR one) and the dithered captures in the shader, including the clamp a UNORM store performs.
inline uint32_t DitheredCode(float value, uint32_t x, uint32_t y, uint32_t maxCode = 255,
                             DitherMap map = DitherMap::BlueNoise)
{
    const float offset = map == DitherMap::Bayer8 ? Bayer8Offset(x, y) : BlueNoiseOffset(x, y);
    float code = value * static_cast<float>(maxCode) + offset + 0.5f;
    if (code < 0.0f) code = 0.0f;
    const float top = static_cast<float>(maxCode);
    if (code > top) code = top;
    return static_cast<uint32_t>(code);
}

