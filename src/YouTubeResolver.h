enum class ResolveError {
    None,
    InvalidUrl,
    HelperMissing,
    StartFailed,
    TimedOut,
    Cancelled,
    OutputTooLarge,
    ExtractionFailed,
    InvalidOutput,
};

enum class YouTubeSourceQuality {
    Auto,
    P2160,
    P1440,
    P1080,
};

// A caption track YouTube publishes for a video, as yt-dlp reports it (P2.42):
// one the uploader wrote, YouTube's speech recognition, or that recognition
// machine-translated. Told apart by the URL YouTube serves it from - kind=asr
// is recognition, tlang is a translation - which is the one place the
// difference is stated rather than guessed from a name.
enum class CaptionKind {
    Manual,
    AutoGenerated,
    AutoTranslated,
};

struct CaptionTrack {
    std::string language;   // yt-dlp's key: "en", "en-orig", "pt-BR"
    std::string name;       // YouTube's own name for it: "English (Original)"
    CaptionKind kind{CaptionKind::Manual};
    std::wstring url;       // WebVTT, on youtube.com or googlevideo.com only

    friend bool operator==(const CaptionTrack&, const CaptionTrack&) = default;
};

// At most this many tracks are kept from one resolve, best first.
inline constexpr size_t kMaximumCaptionTracks = 8;

struct ResolveResult {
    bool ok{false};
    std::wstring mediaUrl;
    std::wstring audioUrl;
    ResolveError error{ResolveError::None};
    std::wstring detail;
    double durationSeconds{};
    // Latest selected stream availability, rounded up to avoid premature access.
    int64_t availableAtUnixSeconds{};
    // Height in pixels of the rung yt-dlp actually selected; zero when unknown.
    int selectedHeight{};
    // Bitrate of that rung in kbps: the video stream's own rate for a merged
    // selection, the whole stream's rate for a progressive one, which is what a
    // legacy 360p fallback offers. Zero when yt-dlp advertised neither.
    double videoKbps{};
    // YouTube age gate in years, 18 on age-restricted videos; zero when none or unknown.
    int ageLimit{};
    // The caption tracks in the viewer's language and in English, best first
    // (OrderCaptionTracks); empty when YouTube has none or yt-dlp said nothing.
    std::vector<CaptionTrack> captions;
};

bool IsSupportedYouTubeUrl(std::wstring_view value);
std::string CanonicalYouTubeVideoId(std::wstring_view value);
std::string StableYouTubeStreamIdentity(std::wstring_view mediaUrl,
                                        std::wstring_view audioUrl);
std::wstring_view YouTubeResolveErrorMessageKey(ResolveError error);
// `captionLanguage` is the viewer's interface language ("en", "de", "zh-Hans"),
// which orders the caption tracks.
ResolveResult ParseResolverOutput(std::string_view stdoutBytes, DWORD exitCode,
                                  std::wstring_view captionLanguage = L"en");
// The --sub-langs yt-dlp is given: the interface language and English, each
// with its regional and script variants and its recognition original
// ("de-DE", "zh-Hans", "en-orig"), and nothing translated from a third
// language ("en-ja" is Japanese machine-translated into English).
std::wstring YouTubeCaptionLanguages(std::wstring_view interfaceLanguage);
// yt-dlp's requested_subtitles as JSON: the WebVTT tracks on trusted hosts,
// ordered and capped (kMaximumCaptionTracks). Anything else is dropped.
std::vector<CaptionTrack> ParseCaptionTracks(std::string_view json, std::wstring_view interfaceLanguage);
// https, no user name, the default port, and a youtube.com or googlevideo.com
// host: the only places a caption is fetched from.
bool IsTrustedCaptionUrl(std::wstring_view url);
// The host and the path with its query, for an HTTPS GET of a trusted caption URL.
struct CaptionRequest {
    std::wstring host;
    std::wstring path;
};
std::optional<CaptionRequest> CaptionRequestFor(std::wstring_view url);
// A body that is a WebVTT file: the signature, after an optional byte-order mark.
bool LooksLikeWebVtt(std::string_view body);
// yt-dlp's stderr as one log line: at most the bytes captured (the rest are
// only counted in `totalBytes`), line breaks folded to " | ", anything outside
// printable ASCII shown as '?'. Empty when there was nothing.
std::string SummarizeResolverStderr(std::string_view captured, size_t totalBytes);
std::wstring_view YouTubeFormatSelector(YouTubeSourceQuality quality);
#ifdef YOUTUBE_RESOLVER_TESTING
std::wstring QuoteWindowsArgument(std::wstring_view argument);
std::vector<std::wstring> BuildYouTubeResolverArguments(
    const std::filesystem::path& helperDirectory,
    std::wstring_view youtubeUrl,
    YouTubeSourceQuality quality,
    std::wstring_view captionLanguage = L"en");
#endif

class YouTubeResolver {
public:
    YouTubeResolver();
    ~YouTubeResolver();

    YouTubeResolver(const YouTubeResolver&) = delete;
    YouTubeResolver& operator=(const YouTubeResolver&) = delete;

    ResolveResult Resolve(std::wstring_view youtubeUrl, std::stop_token stop);
    ResolveResult Resolve(std::wstring_view youtubeUrl, YouTubeSourceQuality quality,
                          std::stop_token stop);
    void Cancel();
    // The interface language the caption tracks are asked for and ordered by.
    void SetCaptionLanguage(std::wstring_view language);

#ifdef YOUTUBE_RESOLVER_TESTING
    enum class FailureStage {
        None,
        PipeHandlesOwned,
        JobAssignment,
        Resume,
        PipeRead,
    };
#endif

private:
#ifdef YOUTUBE_RESOLVER_TESTING
    friend struct YouTubeResolverTestAccess;

    struct Settings {
        std::filesystem::path helperDirectory;
        std::chrono::milliseconds deadline{std::chrono::seconds{45}};
        std::chrono::milliseconds pollInterval{std::chrono::milliseconds{25}};
        std::chrono::milliseconds shutdownWait{std::chrono::seconds{2}};
        FailureStage failureStage{FailureStage::None};
    };

    explicit YouTubeResolver(Settings settings);
#endif

    std::filesystem::path helperDirectory_;
    std::chrono::milliseconds deadline_{std::chrono::seconds{45}};
    std::chrono::milliseconds pollInterval_{std::chrono::milliseconds{25}};
    std::chrono::milliseconds shutdownWait_{std::chrono::seconds{2}};
#ifdef YOUTUBE_RESOLVER_TESTING
    FailureStage failureStage_{FailureStage::None};
    // What the last Resolve logged of the helper's stderr.
    std::string lastStderrSummary_;
#endif
    std::wstring captionLanguage_{L"en"};
    std::mutex resolveMutex_;
    std::mutex stateMutex_;
    HANDLE activeJob_{nullptr};
    bool resolving_{false};
    bool cancelRequested_{false};
};
